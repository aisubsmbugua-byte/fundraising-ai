-- Ruling 0038: a command is a decision made in words, and a decision gate is
-- decided only on what the user was shown. STATE item 92.
--
-- One table: assistant_command_events -- the append-only record of every
-- command the assistant executes, refuses or fails, and of every click-driven
-- restore of text a command replaced (ruling 0038 clause 5: "names who, the
-- user's message, the quoted words, the ability, the exact payload, and the
-- outcome; where a write replaced content, it holds what was replaced.
-- Records are append-only.").
--
-- Why an event log rather than one row per command. The record must exist
-- BEFORE the effect (a command that ran and left no trace is the failure this
-- ruling exists to prevent), and append-only forbids updating it afterwards
-- to say how it ended. So a command is two rows, tied by command_id:
--
--   started    born BEFORE the effect. It carries the quoted words, the exact
--              payload and -- where the write is about to replace something --
--              what it will replace (`previous`), so a crash mid-effect still
--              leaves both.
--   executed | failed
--              written after, once. executed means the existing entry point
--              returned success; failed means it threw or returned an error.
--
-- and a command refused BEFORE the effect (the quoted words are not in the
-- user's message, the turn's cap is reached, a gate's subject was not shown
-- earlier, the content changed since it was shown, a guard failed) is ONE
-- row, `refused`, because there is no effect for a started row to precede.
-- A killed command is a `started` row with no terminal row -- the same
-- encoding ai_runs uses for a killed run (ruling 0026): nobody observes a
-- kill, so nobody writes one.
--
-- Enforcement, in the database as well as in code (a policy is not the only
-- wall, per 0080):
--   * RLS: insert and select only, scoped by organization AND author. There is
--     NO update policy and NO delete policy anywhere.
--   * A BEFORE UPDATE trigger rejects every update for every role, the
--     service role included -- the table is append-only, not merely
--     unpolicied.
--   * A BEFORE INSERT trigger (security definer, fixed search_path, the shape
--     0066 / 0078 / 0080 use) checks the cross-table facts a foreign key
--     cannot: the thread, the user's message and the assistant's message are
--     all in this row's organization and thread, the author owns the thread,
--     a COMMAND is recorded only by a RUNNING assistant turn, and a terminal
--     executed/failed row follows a started row of the same command, same
--     author, same ability.
--   * Partial unique indexes: one started row and one terminal row per
--     command_id.
--   * The ability vocabulary is closed here as it is in code. Adding one is a
--     reviewed migration, not a prompt.
--
-- subject_table / subject_id are soft references (the subject is a prospect,
-- a supporter, a draft or a strategy run depending on the ability, which a
-- single foreign key cannot express; and a deleted subject must not cascade
-- away the record of what was done to it).
--
-- Additive under ruling 0020: one new table, its indexes, functions, triggers
-- and policies. No existing table, column, function or policy is touched, so
-- it is safe to apply ahead of its code. Code deployed ahead of this migration
-- answers a command with "setup pending -- apply migration 0081" and writes
-- nothing.

create table assistant_command_events (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references organizations (id) default my_organization_id(),
  created_by uuid not null default auth.uid() references auth.users (id),
  -- Generated by code; ties a started row to its terminal row. Not a foreign
  -- key: it names the command, which is exactly these rows.
  command_id uuid not null,
  -- started | executed | failed | refused
  event text not null,
  -- command: executed by a tool call on the user's words. click: a
  -- click-driven restore (a user decision, not a command).
  origin text not null default 'command',
  thread_id uuid not null references assistant_threads (id) on delete cascade,
  -- The user's message that authorized it, and the assistant turn that ran it.
  user_message_id uuid not null references assistant_messages (id) on delete cascade,
  assistant_message_id uuid not null references assistant_messages (id) on delete cascade,
  ability text not null,
  subject_table text,
  subject_id uuid,
  -- The exact validated arguments (the quotation is its own column).
  payload jsonb not null,
  -- The user's own words that authorized it, as they typed them. Null for a
  -- click-driven restore, which is authorized by the click itself.
  quote text,
  -- Born with the started row: what the write is about to replace.
  previous jsonb,
  -- Written with the terminal row: what the entry point reported.
  result jsonb,
  error_note text,
  -- A restore points at the command it undoes.
  restores_command_id uuid,
  created_at timestamptz not null default now()
);

alter table assistant_command_events
  add constraint assistant_command_events_event_check
  check (event in ('started', 'executed', 'failed', 'refused'));

alter table assistant_command_events
  add constraint assistant_command_events_origin_check
  check (origin in ('command', 'click'));

-- The closed list of recorded actions, enforced here as well as in code.
alter table assistant_command_events
  add constraint assistant_command_events_ability_check
  check (
    ability in (
      'add_prospect',
      'edit_draft',
      'revise_draft_with_feedback',
      'push_back_on_strategy',
      'generate_outreach_draft',
      'unapprove_draft',
      'log_prospect_interaction',
      'set_prospect_next_action',
      'log_supporter_interaction',
      'set_prospect_ask_amount',
      'approve_strategy',
      'approve_draft',
      'restore_draft_text'
    )
  );

alter table assistant_command_events
  add constraint assistant_command_events_subject_check
  check (
    (subject_table is null and subject_id is null)
    or (subject_table in ('prospects', 'supporters', 'drafts', 'strategy_runs') and subject_id is not null)
  );

alter table assistant_command_events
  add constraint assistant_command_events_json_check
  check (
    jsonb_typeof(payload) = 'object'
    and (previous is null or jsonb_typeof(previous) = 'object')
    and (result is null or jsonb_typeof(result) = 'object')
  );

-- Shape by event. `previous` lives on the started row only, and a started row
-- carries no outcome; a failure or a refusal always says why.
alter table assistant_command_events
  add constraint assistant_command_events_event_shape_check
  check (
    (event = 'started' and result is null and error_note is null)
    or (event = 'executed' and error_note is null and previous is null)
    or (event in ('failed', 'refused') and error_note is not null and previous is null)
  );

-- A command is authorized by the user's words, quoted; a restore by a click,
-- naming what it undoes -- and only a restore uses the restore ability.
alter table assistant_command_events
  add constraint assistant_command_events_origin_shape_check
  check (
    (
      origin = 'command'
      and quote is not null
      and char_length(quote) between 1 and 500
      and restores_command_id is null
      and ability <> 'restore_draft_text'
    )
    or (
      origin = 'click'
      and quote is null
      and restores_command_id is not null
      and ability = 'restore_draft_text'
    )
  );

create unique index assistant_command_events_one_started_idx
  on assistant_command_events (command_id) where event = 'started';
create unique index assistant_command_events_one_terminal_idx
  on assistant_command_events (command_id) where event <> 'started';
create index assistant_command_events_thread_idx on assistant_command_events (thread_id, created_at);
create index assistant_command_events_user_message_idx on assistant_command_events (user_message_id);
create index assistant_command_events_restores_idx on assistant_command_events (restores_command_id) where restores_command_id is not null;
create index assistant_command_events_organization_id_idx on assistant_command_events (organization_id);

comment on table assistant_command_events is
  'Ruling 0038 clause 5: the append-only record of assistant commands. A started row is born BEFORE the effect and holds the quoted words, the exact payload and what will be replaced; a terminal row (executed, failed) follows once; a command refused before its effect is one refused row. Insert and select only; no update or delete policy; updates rejected for every role.';

-- Append-only for every role, the service role included.
create function assistant_command_events_reject_update() returns trigger as $$
begin
  raise exception 'assistant_command_events: the command record is append-only -- rows are never updated';
end;
$$ language plpgsql;

create trigger assistant_command_events_append_only
  before update on assistant_command_events
  for each row execute function assistant_command_events_reject_update();

-- Cross-table integrity (see the header). A foreign key check runs as the
-- table owner and does not respect RLS, so the policies below stop one org
-- READING another's row and do not stop one POINTING AT it; this closes that
-- at birth.
create function enforce_assistant_command_event() returns trigger as $$
declare
  t_org uuid;
  t_owner uuid;
  u_org uuid;
  u_thread uuid;
  u_role text;
  a_org uuid;
  a_thread uuid;
  a_role text;
  a_status text;
  s_org uuid;
  s_owner uuid;
  s_ability text;
  s_thread uuid;
  s_origin text;
  s_assistant uuid;
  has_terminal boolean;
begin
  select organization_id, created_by into t_org, t_owner from assistant_threads where id = new.thread_id;
  if new.organization_id is distinct from t_org then
    raise exception 'organization_id must match the referenced thread''s organization_id';
  end if;
  if new.created_by is distinct from t_owner then
    raise exception 'a command record must be written by the user who owns the thread';
  end if;

  select organization_id, thread_id, role into u_org, u_thread, u_role
    from assistant_messages where id = new.user_message_id;
  if new.organization_id is distinct from u_org
     or new.thread_id is distinct from u_thread
     or u_role is distinct from 'user' then
    raise exception 'the authorizing message must be a user message of the same thread and organization';
  end if;

  select organization_id, thread_id, role, status into a_org, a_thread, a_role, a_status
    from assistant_messages where id = new.assistant_message_id;
  if new.organization_id is distinct from a_org
     or new.thread_id is distinct from a_thread
     or a_role is distinct from 'assistant' then
    raise exception 'the recording turn must be an assistant message of the same thread and organization';
  end if;

  -- A command is recorded during the turn that ran it, never afterwards. (A
  -- click-driven restore is recorded later, against a finished turn.)
  if new.origin = 'command' and a_status is distinct from 'running' then
    raise exception 'a command can only be recorded by a running assistant turn';
  end if;

  if new.event = 'started' then
    select exists (
      select 1 from assistant_command_events where command_id = new.command_id and event <> 'started'
    ) into has_terminal;
    if has_terminal then
      raise exception 'a command that already has an outcome cannot be started again';
    end if;
    return new;
  end if;

  -- A terminal row: it must follow the started row of the SAME command, the
  -- same author, ability, thread, turn and origin. A refusal that never
  -- started has no started row to follow and is the only terminal row that
  -- may stand alone.
  select organization_id, created_by, ability, thread_id, origin, assistant_message_id
    into s_org, s_owner, s_ability, s_thread, s_origin, s_assistant
    from assistant_command_events where command_id = new.command_id and event = 'started';
  if found then
    if new.organization_id is distinct from s_org
       or new.created_by is distinct from s_owner
       or new.ability is distinct from s_ability
       or new.thread_id is distinct from s_thread
       or new.origin is distinct from s_origin
       or new.assistant_message_id is distinct from s_assistant then
      raise exception 'a terminal row must match the started row of the same command';
    end if;
  elsif new.event in ('executed', 'failed') then
    raise exception 'an executed or failed row must follow a started row of the same command';
  end if;
  return new;
end;
$$ language plpgsql security definer set search_path = public;

create trigger assistant_command_events_refs_match
  before insert on assistant_command_events
  for each row execute function enforce_assistant_command_event();

-- Tenant isolation. Hard rule 6, following 0033_multi_tenant_rls.sql and
-- 0080. Scoped by organization AND author: a thread is personal to the user
-- the assistant acts as, and so is its record.
alter table assistant_command_events enable row level security;

create policy "users can record their own assistant commands"
  on assistant_command_events for insert
  to authenticated
  with check (organization_id = my_organization_id() and created_by = auth.uid());

create policy "users can read their own assistant command record"
  on assistant_command_events for select
  to authenticated
  using (organization_id = my_organization_id() and created_by = auth.uid());
